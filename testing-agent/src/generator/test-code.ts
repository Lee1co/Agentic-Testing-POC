import ts from 'typescript';
import { findExternalUrls } from '../browser/url-guard.js';

/** Static analysis of generated Playwright code. Pure functions, no I/O. */

export interface TestFileMeta {
  testId: string;
  appId: string;
  objective: string;
  version: number;
  requirementIds: string[];
  acceptanceCriteriaIds: string[];
  generatedBy: string;
}

const HEADER_START = '/* @agentic-test';
const HEADER_END = '@end-agentic-test */';

export function composeTestFile(meta: TestFileMeta, body: string): string {
  const lines = [
    HEADER_START,
    ` * Generated by the agentic testing framework. Do not edit by hand: healing creates new versions.`,
    ` * testId: ${meta.testId}`,
    ` * app: ${meta.appId}`,
    ` * objective: ${meta.objective.replace(/\*\//g, '* /').replace(/\n/g, ' ')}`,
    ` * version: ${meta.version}`,
    ` * requirements: ${meta.requirementIds.join(', ') || '(none)'}`,
    ` * acceptanceCriteria: ${meta.acceptanceCriteriaIds.join(', ') || '(none)'}`,
    ` * generatedBy: ${meta.generatedBy}`,
    ` ${HEADER_END}`,
  ];
  return `${lines.join('\n')}\n${stripHeader(body).trim()}\n`;
}

export function stripHeader(code: string): string {
  const start = code.indexOf(HEADER_START);
  const end = code.indexOf(HEADER_END);
  if (start === -1 || end === -1) return code;
  return (code.slice(0, start) + code.slice(end + HEADER_END.length)).trimStart();
}

/** Removes a markdown fence if the model wrapped the code in one. */
export function unwrapCodeFence(code: string): string {
  const match = code.match(/^\s*```(?:ts|typescript)?\s*\n([\s\S]*?)\n```\s*$/);
  return match?.[1] ?? code;
}

const FORBIDDEN_PATTERNS: Array<{ pattern: RegExp; reason: string }> = [
  { pattern: /\bwaitForTimeout\s*\(/, reason: 'arbitrary sleeps (waitForTimeout) are not allowed' },
  { pattern: /\bsetTimeout\s*\(/, reason: 'setTimeout-based waiting is not allowed' },
  { pattern: /\brequire\s*\(/, reason: 'require() is not allowed' },
  { pattern: /\bimport\s*\(/, reason: 'dynamic import() is not allowed' },
  { pattern: /\bprocess\s*\./, reason: 'access to process is not allowed' },
  { pattern: /child_process|node:fs|['"]fs['"]|node:net|node:http/, reason: 'Node system modules are not allowed' },
  { pattern: /\beval\s*\(|new\s+Function\s*\(/, reason: 'dynamic code evaluation is not allowed' },
  { pattern: /\.route\s*\(|routeFromHAR|unroute/, reason: 'network interception is reserved for the framework harness' },
  { pattern: /\btest\.(only|skip|fixme)\b/, reason: 'test.only/skip/fixme are not allowed' },
  { pattern: /\bexpect\.soft\s*\(/, reason: 'soft assertions are not allowed' },
];

const ALLOWED_IMPORT = /^import\s*\{[^}]*\}\s*from\s*['"]\.\.\/fixtures(\.js|\.ts)?['"];?$/;

export interface ValidationOptions {
  allowedHosts: string[];
  minAssertions?: number;
  /** Markers (e.g. acceptance-criteria ids) that must appear in the code. */
  requiredMarkers?: string[];
}

export interface ValidationResult {
  valid: boolean;
  errors: string[];
  warnings: string[];
  assertionCount: number;
}

export function syntaxErrors(code: string): string[] {
  const output = ts.transpileModule(code, {
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
    fileName: 'candidate.spec.ts',
  });
  return (output.diagnostics ?? []).map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
}

export function countAssertions(code: string): number {
  return (code.match(/\bexpect\s*\(/g) ?? []).length;
}

export function validateTestCode(rawCode: string, options: ValidationOptions): ValidationResult {
  const code = stripHeader(rawCode);
  const errors: string[] = [];
  const warnings: string[] = [];

  const importLines = code.split('\n').filter((line) => /^\s*import\s/.test(line));
  if (importLines.length === 0) errors.push("missing `import { test, expect } from '../fixtures';`");
  for (const line of importLines) {
    if (!ALLOWED_IMPORT.test(line.trim())) {
      errors.push(`only "import { test, expect } from '../fixtures'" is allowed, found: ${line.trim()}`);
    }
  }
  if (!/\btest\s*\(/.test(code)) errors.push('no test(...) block found');

  const assertionCount = countAssertions(code);
  const minAssertions = options.minAssertions ?? 2;
  if (assertionCount < minAssertions) errors.push(`expected at least ${minAssertions} expect() assertions, found ${assertionCount}`);

  for (const { pattern, reason } of FORBIDDEN_PATTERNS) {
    if (pattern.test(code)) errors.push(reason);
  }
  const external = findExternalUrls(code, options.allowedHosts);
  if (external.length) errors.push(`references non-approved hosts: ${external.join(', ')}`);

  for (const marker of options.requiredMarkers ?? []) {
    if (!code.includes(marker)) errors.push(`must reference ${marker} (e.g. in a test.step title) for traceability`);
  }
  if (/\.locator\(\s*['"`](\/\/|xpath=)/.test(code)) warnings.push('XPath locators are brittle; prefer roles, labels or test ids');
  if (/nth-child|:nth\(/.test(code)) warnings.push('positional CSS selectors are brittle');

  errors.push(...syntaxErrors(code).map((message) => `TypeScript syntax error: ${message}`));
  return { valid: errors.length === 0, errors, warnings, assertionCount };
}

/** Matchers used by expect(), e.g. "toBeVisible", "not.toBeVisible", "toHaveURL". */
export function assertionSignature(code: string): string[] {
  const matches = stripHeader(code).match(/\.(not\.)?(to[A-Z][A-Za-z]*)\s*\(/g) ?? [];
  return matches.map((m) => m.replace(/^\./, '').replace(/\s*\($/, '')).sort();
}

export interface AssertionGuardResult {
  ok: boolean;
  violations: string[];
}

/**
 * A repair must not weaken a test: every assertion matcher in the original (including negated ones)
 * must still be present, the number of expect() calls must not drop, and traceability markers stay.
 */
export function checkAssertionsPreserved(original: string, candidate: string, markers: string[] = []): AssertionGuardResult {
  const violations: string[] = [];
  const before = assertionSignature(original);
  const after = [...assertionSignature(candidate)];
  for (const matcher of before) {
    const index = after.indexOf(matcher);
    if (index === -1) violations.push(`assertion ${matcher} was removed`);
    else after.splice(index, 1);
  }
  const beforeCount = countAssertions(stripHeader(original));
  const afterCount = countAssertions(stripHeader(candidate));
  if (afterCount < beforeCount) violations.push(`expect() count dropped from ${beforeCount} to ${afterCount}`);
  for (const marker of markers) {
    if (stripHeader(original).includes(marker) && !stripHeader(candidate).includes(marker)) {
      violations.push(`traceability marker ${marker} was removed`);
    }
  }
  return { ok: violations.length === 0, violations };
}

/** Extracts the locator expressions used by a test, for knowledge persistence and diagnostics. */
export function extractLocators(code: string): string[] {
  const pattern = /\b(getByRole|getByLabel|getByText|getByTestId|getByPlaceholder|getByTitle|getByAltText|locator)\(([^()]*(?:\([^()]*\)[^()]*)*)\)/g;
  const found = new Set<string>();
  for (const match of stripHeader(code).matchAll(pattern)) {
    found.add(`${match[1]}(${match[2]!.replace(/\s+/g, ' ').trim()})`);
  }
  return [...found];
}

export function extractTitle(code: string): string {
  return code.match(/\btest\s*\(\s*['"`]([^'"`]+)['"`]/)?.[1] ?? 'generated test';
}

/**
 * Title of the most recent `test.step(...)` opened at or before a 1-based line of the full spec file.
 * Steps are assumed to be sequential (not nested), which is how generated tests are structured.
 */
export function stepTitleAtLine(code: string, line: number): string | undefined {
  let title: string | undefined;
  for (const [index, text] of code.split('\n').entries()) {
    if (index + 1 > line) break;
    const match = text.match(/\btest\.step\(\s*(['"`])(.*?)\1/);
    if (match) title = match[2];
  }
  return title;
}

/** Acceptance-criteria ids named by the step title that contains the failing statement; empty when outside an AC step. */
export function failingAcceptanceCriteria(code: string, failureLines: number[]): string[] {
  const ids = new Set<string>();
  for (const line of failureLines) {
    for (const id of stepTitleAtLine(code, line)?.match(/\bAC-\d+\b/g) ?? []) ids.add(id);
  }
  return [...ids];
}
